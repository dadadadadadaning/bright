function addShape(spec) {
  return slide.shapes.add(spec);
}

function addText(name, text, position, options = {}) {
  const shape = addShape({
    geometry: "textbox",
    name,
    position,
    fill: options.fill ?? "none",
    line: options.line ?? { fill: "none", width: 0 },
  });
  shape.text = text;
  shape.text.style = {
    typeface: options.typeface ?? "Arial",
    fontSize: options.fontSize ?? 18,
    bold: options.bold ?? false,
    color: options.color ?? TEXT,
    alignment: options.alignment ?? "left",
    verticalAlignment: options.verticalAlignment ?? "middle",
    wrap: options.wrap ?? "square",
    autoFit: options.autoFit ?? "shrinkText",
    insets: options.insets ?? { top: 3, right: 5, bottom: 3, left: 5 },
  };
  return shape;
}

function addRect(name, position, fill, lineFill = LINE, radius = 8) {
  return addShape({
    geometry: "roundRect",
    name,
    position,
    fill,
    line: { style: "solid", fill: lineFill, width: 1.1 },
    borderRadius: radius,
  });
}

function addBadge(number, left, top, fill) {
  const badge = addShape({
    geometry: "ellipse",
    name: `Step ${number}`,
    position: { left, top, width: 34, height: 34 },
    fill,
    line: { fill: "none", width: 0 },
  });
  badge.text = String(number);
  badge.text.style = {
    typeface: "Arial", fontSize: 17, bold: true, color: WHITE,
    alignment: "center", verticalAlignment: "middle", autoFit: "none",
    insets: { top: 0, right: 0, bottom: 0, left: 0 },
  };
}

function addArrow(left, top, width = 44, height = 26, fill = NAVY) {
  addShape({
    geometry: "rightArrow",
    position: { left, top, width, height },
    fill,
    line: { fill: "none", width: 0 },
  });
}

